// Local application browser test, in an isolated headless profile.
const {chromium}=require(process.env.MOUNT_PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8765');
 await page.waitForSelector('.axis-card',{state:'attached'});
 await page.locator('[data-axis-tab="azimuth"]').click();
 await page.getByText('Live stream',{exact:true}).waitFor();
 assert.equal(await page.locator('.axis-card').count(),4);
 await page.screenshot({path:'runtime/dashboard-desktop.png',fullPage:true});
 const az=page.locator('[data-axis="azimuth"]');
 const liveState=await (await page.request.get('http://localhost:8765/api/state')).json();
 await az.locator('.metric-select').selectOption('velocity');
 if(liveState.drive.mode==='simulation')await az.locator('.command-legend').waitFor({state:'visible'});
 await page.getByRole('button',{name:'Pause graphs'}).click();
 await page.getByRole('button',{name:'Resume live'}).waitFor();
 await page.getByRole('button',{name:'Resume live'}).click({noWaitAfter:true});
 await page.getByRole('button',{name:'Pause graphs'}).waitFor();
 if(liveState.drive.mode==='hardware'){
  assert.equal(liveState.drive.identity,'25262718');
  assert.ok(liveState.axes.every(a=>a.valid));
  assert.equal(await page.locator('#stop-all').isDisabled(),false);
  assert.equal(await az.locator('.goto-button').isDisabled(),true);
  await az.locator('.metric-select').selectOption('current');
  await page.getByRole('button',{name:'Drive connection',exact:true}).click();
  assert.equal(await page.locator('#poll-interval').inputValue(),'5');
  assert.equal(await page.locator('#baud').inputValue(),'921600');
  await page.getByRole('button',{name:'Close connection settings'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'runtime/dashboard-mobile.png',fullPage:true});
  const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(dims.scroll<=dims.width);
  const target=await az.locator('input').boundingBox();assert.ok(target.width>=50);
  assert.deepEqual(errors,[]);
  await browser.close();console.log('Real-hardware dashboard passed: live data, metric selection, pause, connection settings, control buttons available without activating hardware, mobile.');return;
 }
 await az.locator('input').fill('200');
 await az.getByRole('button',{name:'Go',exact:true}).click();
 await az.getByText('SLEWING',{exact:true}).waitFor();
 await page.getByRole('button',{name:'STOP ALL',exact:true}).click();
 await az.getByText('IDLE',{exact:true}).waitFor();
 await az.locator('.motor-button').click();
 await az.getByText('DISABLED',{exact:true}).waitFor();
 assert.equal(await az.locator('.jog-button').first().isDisabled(),true);
 await az.locator('.motor-button').click();
 await az.getByText('IDLE',{exact:true}).waitFor();
 const jog=az.getByRole('button',{name:'Hold to jog Azimuth positive'});
 const box=await jog.boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
 await az.getByText('JOGGING',{exact:true}).waitFor();await page.mouse.up();await az.getByText('IDLE',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Drive connection',exact:true}).click();
 await page.getByRole('button',{name:'Disconnect',exact:true}).click();
 await page.getByText('Disconnected',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'STOP ALL',exact:true}).isDisabled(),true);
 await page.getByRole('button',{name:'Drive connection',exact:true}).click();
 await page.getByRole('button',{name:'Connect drive',exact:true}).click();
 await page.locator('#connection-label').filter({hasText:'Simulation'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.waitForFunction(()=>document.querySelector('.chart-range').textContent.includes('window') && document.querySelector('canvas').width>0);
 await page.getByRole('button',{name:'Azimuth axis details'}).click();
 await page.getByRole('button',{name:'Close axis detail'}).click();
 await page.screenshot({path:'runtime/dashboard-mobile.png',fullPage:true});
 const dims=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));assert.ok(dims.scroll<=dims.width,`Horizontal overflow: ${JSON.stringify(dims)}`);
 const target=await az.locator('input').boundingBox();assert.ok(target.width>=50,'Mobile target input must remain usable');
 assert.deepEqual(errors,[]);
 await browser.close();console.log('Dashboard smoke passed: stream, dropdown, pause, goto, enable, jog, stop, reconnect, mobile width.');
})().catch(e=>{console.error(e);process.exit(1);});
